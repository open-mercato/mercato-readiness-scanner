import type { FindingStatus, RuleResult, ScanReport } from './types.js'

const ICONS: Record<FindingStatus, string> = { pass: '✅', fail: '❌', warning: '⚠️ ', skipped: '⏭️ ' }
const STATUS_ORDER: FindingStatus[] = ['fail', 'warning', 'skipped', 'pass']

type Colors = {
  bold: (value: string) => string
  dim: (value: string) => string
  status: (status: FindingStatus, value: string) => string
}

function colorizer(enabled: boolean): Colors {
  const wrap = (code: number) => (value: string): string => enabled ? `\u001B[${code}m${value}\u001B[0m` : value
  const statusCodes: Record<FindingStatus, number> = { pass: 32, fail: 31, warning: 33, skipped: 90 }
  return { bold: wrap(1), dim: wrap(2), status: (status, value) => wrap(statusCodes[status])(value) }
}

function resultLine(result: RuleResult, colors: Colors): string {
  return `${ICONS[result.status]} ${colors.status(result.status, result.title)} ${colors.dim(`[${result.id} · ${result.severity}]`)}`
}

export function formatTerminal(report: ScanReport, color = true): string {
  const colors = colorizer(color)
  const lines = [
    colors.bold('Open Mercato production readiness'),
    colors.dim(`Target: ${report.target} · Scanner ${report.tool.version} · ${report.scannedAt}`),
    '',
    `${ICONS.fail} ${report.summary.fail} failed   ${ICONS.warning} ${report.summary.warning} review   ${ICONS.pass} ${report.summary.pass} passed   ${ICONS.skipped} ${report.summary.skipped} skipped`,
  ]
  for (const status of STATUS_ORDER) {
    const results = report.results.filter((result) => result.status === status)
    if (!results.length) continue
    lines.push('', colors.bold(status === 'pass' ? 'Configuration checks passed' : status === 'fail' ? 'Best practices to address' : status === 'warning' ? 'Needs live or operator verification' : 'Skipped or disabled'))
    for (const result of results) {
      lines.push(resultLine(result, colors), `   ${result.summary}`)
      for (const evidence of result.evidence) lines.push(colors.dim(`   • ${evidence}`))
      if (status === 'fail' || status === 'warning') lines.push(`   Fix: ${result.remediation}`, `   Docs: ${result.docsUrl}`)
    }
  }
  return `${lines.join('\n')}\n`
}

function escapeCell(value: string): string {
  return value.replaceAll('|', '\\|').replaceAll('\n', ' ')
}

export function formatMarkdown(report: ScanReport): string {
  const lines = [
    '# Open Mercato production readiness report',
    '',
    `- Target: \`${report.target}\``,
    `- Scanned: ${report.scannedAt}`,
    `- Scanner: \`${report.tool.name}@${report.tool.version}\``,
    `- Summary: ${report.summary.fail} failed, ${report.summary.warning} need review, ${report.summary.pass} passed, ${report.summary.skipped} skipped`,
    '',
    '| Status | Rule | Severity | Result |',
    '|---|---|---|---|',
  ]
  for (const result of report.results) lines.push(`| ${ICONS[result.status]} ${result.status} | [${result.id}](${result.docsUrl}) | ${result.severity} | ${escapeCell(result.summary)} |`)
  lines.push('')
  for (const result of report.results.filter((entry) => entry.status !== 'pass')) {
    lines.push(`## ${ICONS[result.status]} ${result.title}`, '', `**Rule:** [${result.id}](${result.docsUrl})  `, `**Severity:** ${result.severity}  `, `**Status:** ${result.status}`, '', result.summary, '')
    if (result.evidence.length) {
      lines.push('Evidence:', '')
      for (const evidence of result.evidence) lines.push(`- ${evidence}`)
      lines.push('')
    }
    lines.push(`Remediation: ${result.remediation}`, '')
  }
  lines.push('---', '', 'Generated by `@open-mercato/readiness-scanner`. Configuration and permission checks are not proof of live production readiness. Production environment values were inspected locally and are never included in this report.', '')
  return lines.join('\n')
}

export function formatJson(report: ScanReport): string {
  return `${JSON.stringify(report, null, 2)}\n`
}
